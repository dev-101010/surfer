const DICTIONARIES = {de, en};
const LANGUAGES = Object.keys(DICTIONARIES);
const LOCALES = {de: 'de-DE', en: 'en-GB'};

/** System language: German if the OS locale is German, English otherwise. */
function detectLanguage() {
    try {
        const locale = Intl.DateTimeFormat().resolvedOptions().locale || '';
        return locale.toLowerCase().startsWith('de') ? 'de' : 'en';
    } catch {
        return 'en';
    }
}

function resolveLanguage(preference) {
    return LANGUAGES.includes(preference) ? preference : detectLanguage();
}

let current = detectLanguage();

function setLanguage(preference) {
    current = resolveLanguage(preference);
    return current;
}

function getLanguage() {
    return current;
}

function format(template, params) {
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : m));
}

/** Translates `key` into the current language. Unknown keys fall back to English, then to the key. */
function t(key, params) {
    const dict = DICTIONARIES[current];
    const template = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : (en[key] !== undefined ? en[key] : key);
    return format(template, params);
}

/** All strings of one language (sent to the control window and toolbars). */
function strings(lang = current) {
    return {...en, ...DICTIONARIES[lang]};
}

module.exports = {t, setLanguage, getLanguage, resolveLanguage, detectLanguage, strings, LANGUAGES, LOCALES, DICTIONARIES};
